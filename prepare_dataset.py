"""
Prepares the dataset in YOLO format for tower detection.

Steps:
1. Resizes all images to a uniform size (640x640 for YOLOv8)
2. Splits into train/val/test (70/20/10)
3. Creates YOLO directory structure
4. Generates placeholder annotation files (empty .txt files)
   -> You'll need to annotate these with bounding boxes using a labeling tool

YOLO directory structure:
  dataset/
    images/
      train/
      val/
      test/
    labels/
      train/
      val/
      test/
    data.yaml
"""

import os
import random
import shutil
from pathlib import Path

try:
    from PIL import Image
    HAS_PIL = True
except ImportError:
    HAS_PIL = False
    print("WARNING: Pillow not installed. Images will be copied without resizing.")

SAMPLE_DIR = Path(r"a:\projects\ksit hackathon\sample")
DATASET_DIR = Path(r"a:\projects\ksit hackathon\dataset")
IMG_SIZE = 640  # YOLOv8 default input size
SEED = 42
TRAIN_RATIO = 0.70
VAL_RATIO = 0.20
TEST_RATIO = 0.10

IMAGE_EXTENSIONS = {'.jpg', '.jpeg', '.png', '.bmp', '.tiff', '.webp'}


def prepare():
    random.seed(SEED)

    # Collect all image paths
    images = sorted([
        f for f in SAMPLE_DIR.iterdir()
        if f.suffix.lower() in IMAGE_EXTENSIONS
    ])
    print(f"Found {len(images)} images")

    # Shuffle and split
    random.shuffle(images)
    n = len(images)
    n_train = int(n * TRAIN_RATIO)
    n_val = int(n * VAL_RATIO)

    splits = {
        'train': images[:n_train],
        'val': images[n_train:n_train + n_val],
        'test': images[n_train + n_val:],
    }

    for split_name, split_images in splits.items():
        print(f"  {split_name}: {len(split_images)} images")

    # Create directory structure
    for split in ['train', 'val', 'test']:
        (DATASET_DIR / 'images' / split).mkdir(parents=True, exist_ok=True)
        (DATASET_DIR / 'labels' / split).mkdir(parents=True, exist_ok=True)

    # Process images
    for split_name, split_images in splits.items():
        print(f"\nProcessing {split_name}...")
        for img_path in split_images:
            # Normalize filename to lowercase .jpg
            stem = img_path.stem
            out_name = f"{stem}.jpg"
            out_path = DATASET_DIR / 'images' / split_name / out_name
            label_path = DATASET_DIR / 'labels' / split_name / f"{stem}.txt"

            if HAS_PIL:
                try:
                    img = Image.open(img_path)
                    img = img.convert('RGB')
                    # Resize with aspect ratio preservation (letterbox)
                    img = letterbox_resize(img, IMG_SIZE)
                    img.save(out_path, 'JPEG', quality=95)
                except Exception as e:
                    print(f"  ERROR processing {img_path.name}: {e}")
                    continue
            else:
                shutil.copy2(img_path, out_path)

            # Create empty label file (to be annotated later)
            label_path.touch()

        print(f"  Done: {len(split_images)} images -> {DATASET_DIR / 'images' / split_name}")

    # Generate data.yaml for YOLO
    yaml_content = f"""# Tower Detection Dataset
# Auto-generated by prepare_dataset.py

path: {DATASET_DIR.as_posix()}
train: images/train
val: images/val
test: images/test

# Classes
names:
  0: tower
"""
    yaml_path = DATASET_DIR / 'data.yaml'
    yaml_path.write_text(yaml_content)
    print(f"\nGenerated {yaml_path}")
    print("\n[OK] Dataset prepared!")
    print(f"\n[!!]  NEXT: Annotate images with bounding boxes!")
    print(f"   Label files are at: {DATASET_DIR / 'labels'}")
    print(f"   Format: <class_id> <x_center> <y_center> <width> <height> (normalized 0-1)")
    print(f"   Recommended tool: LabelImg, Roboflow, or CVAT")


def letterbox_resize(img, target_size):
    """Resize image to target_size x target_size with letterboxing (gray padding)."""
    w, h = img.size
    scale = min(target_size / w, target_size / h)
    new_w = int(w * scale)
    new_h = int(h * scale)

    img = img.resize((new_w, new_h), Image.LANCZOS)

    # Create gray canvas and paste
    canvas = Image.new('RGB', (target_size, target_size), (114, 114, 114))
    paste_x = (target_size - new_w) // 2
    paste_y = (target_size - new_h) // 2
    canvas.paste(img, (paste_x, paste_y))

    return canvas


if __name__ == '__main__':
    prepare()
